const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '../.env') });
const cloudDb = require('../main/cloudDb');

async function testLiveGoogleAuth() {
    console.log("=== 🔐 Testing Live Supabase Google OAuth Endpoint ===");
    
    try {
        const { data, error } = await cloudDb.auth.signInWithOAuth({
            provider: 'google',
            options: {
                redirectTo: 'http://localhost:54321/callback',
                skipBrowserRedirect: true,
                scopes: 'https://www.googleapis.com/auth/calendar.readonly https://www.googleapis.com/auth/calendar.events.readonly'
            }
        });

        if (error) {
            console.error("❌ Supabase returned an OAuth error:", error.message);
            if (error.message.includes('provider is not enabled') || error.message.includes('Unsupported provider')) {
                console.log("👉 Make sure to paste the new Client ID and Client Secret in Supabase Dashboard (Authentication -> Providers -> Google) and toggle it ON.");
            }
        } else if (data && data.url) {
            console.log("✅ Google OAuth URL successfully generated by Supabase!");
            console.log("🔗 Auth URL:", data.url.substring(0, 120) + '...');
        }
    } catch (e) {
        console.error("Exception:", e.message);
    }
}

testLiveGoogleAuth().catch(console.error);
